function kartuNama(nama, kelas) {
    console.log('===================');
    console.log('Nama : '+nama);
    console.log('Kelas : '+kelas);
    console.log('===================');
}

//1. Fungsi dipanggil 2 kali oleh baris di bawah ini
kartuNama('Athaya', 'X RPL');
kartuNama('Zalfa', 'X RPL 2');

//2. Parameter yang dipanggil adalah nama serta kelas
// argumen adalah nilai asli yang dikirim ke fungsi
// yaitu Athaya, X RPL, Zalfa, X RPL 2

//3. Tidak memakai fungsi return, termasuk jenis void